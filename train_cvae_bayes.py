"""
Class-Conditional VAE Bayesian Classifier for MNIST
====================================================

Pipeline
--------
1. For each class c in {0,...,9}, train a small VAE on MNIST images of that
   class only, modelling the class-conditional density p(x | omega_c).
2. To classify a test image x, apply Bayes' rule:

        P(omega_c | x)  propto  p(x | omega_c) * P(omega_c)

   The class-conditional density is approximated by the variational lower
   bound (ELBO) of class c's VAE; the log-evidence p(x) is the same for every
   class and therefore cancels. The class prior P(omega_c) is estimated as
   the empirical class frequency in the training set (or 1/10 by default).

Notes
-----
* The model is a standard Gaussian VAE with a Bernoulli decoder (sigmoid
  output + binary cross-entropy reconstruction). All code, including the
  training loop, was generated by the AI assistant for AI Assignment #2.
* CPU only. On the test machine (Intel-class laptop, no GPU) the full
  ten-class training completes in a few minutes.
"""

import os
import time
import json
import argparse
from pathlib import Path

import numpy as np
import torch
import torch.nn as nn
import torch.nn.functional as F
from torch.utils.data import DataLoader, Subset
from torchvision import datasets, transforms

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt


# ---------------------------------------------------------------------------
# Model
# ---------------------------------------------------------------------------
class VAE(nn.Module):
    """A small convolutional VAE for 28x28 grayscale images.

    Encoder: 28x28 -> 14x14 -> 7x7 -> latent (mu, logvar)
    Decoder: latent -> 7x7 -> 14x14 -> 28x28 (sigmoid)
    """

    def __init__(self, latent_dim: int = 20):
        super().__init__()
        self.latent_dim = latent_dim

        self.encoder = nn.Sequential(
            nn.Conv2d(1, 32, 3, stride=2, padding=1),  # 28 -> 14
            nn.BatchNorm2d(32),
            nn.ReLU(inplace=True),
            nn.Conv2d(32, 64, 3, stride=2, padding=1),  # 14 -> 7
            nn.BatchNorm2d(64),
            nn.ReLU(inplace=True),
            nn.Flatten(),
        )
        self.fc_mu = nn.Linear(64 * 7 * 7, latent_dim)
        self.fc_logvar = nn.Linear(64 * 7 * 7, latent_dim)

        self.fc_dec = nn.Linear(latent_dim, 64 * 7 * 7)
        self.decoder = nn.Sequential(
            nn.ConvTranspose2d(64, 32, 3, stride=2, padding=1, output_padding=1),  # 7 -> 14
            nn.BatchNorm2d(32),
            nn.ReLU(inplace=True),
            nn.ConvTranspose2d(32, 1, 3, stride=2, padding=1, output_padding=1),  # 14 -> 28
            nn.Sigmoid(),
        )

    def encode(self, x):
        h = self.encoder(x)
        return self.fc_mu(h), self.fc_logvar(h)

    def reparameterize(self, mu, logvar):
        std = torch.exp(0.5 * logvar)
        eps = torch.randn_like(std)
        return mu + eps * std

    def decode(self, z):
        h = self.fc_dec(z).view(-1, 64, 7, 7)
        return self.decoder(h)

    def forward(self, x):
        mu, logvar = self.encode(x)
        z = self.reparameterize(mu, logvar)
        recon = self.decode(z)
        return recon, mu, logvar


# ---------------------------------------------------------------------------
# Loss: reconstruction (BCE-with-logits summed spatially) + KL divergence
# ---------------------------------------------------------------------------
def vae_loss(recon, x, mu, logvar):
    # Reconstruction term summed over pixels then averaged over batch.
    bce = F.binary_cross_entropy(recon, x, reduction="none")
    bce = bce.view(x.size(0), -1).sum(dim=1)
    # KL divergence to N(0, I), summed over latent dims then averaged.
    kld = -0.5 * torch.sum(1 + logvar - mu.pow(2) - logvar.exp(), dim=1)
    return bce.mean(), kld.mean()


# ---------------------------------------------------------------------------
# Data
# ---------------------------------------------------------------------------
def get_class_indices(dataset, num_classes=10):
    """Return a dict {class: list_of_indices} for MNIST train and test sets."""
    by_class = {c: [] for c in range(num_classes)}
    for idx, (_, label) in enumerate(dataset):
        by_class[label].append(idx)
    return by_class


def make_loaders(batch_size=128, root="./_data"):
    transform = transforms.ToTensor()
    train = datasets.MNIST(root=root, train=True, download=True, transform=transform)
    test = datasets.MNIST(root=root, train=False, download=True, transform=transform)
    return train, test


# ---------------------------------------------------------------------------
# Training one class-conditional VAE
# ---------------------------------------------------------------------------
def train_one_class(
    class_id: int,
    train_dataset,
    indices,
    *,
    epochs: int,
    batch_size: int,
    lr: float,
    device: torch.device,
    latent_dim: int,
    seed: int = 0,
):
    torch.manual_seed(seed + class_id)
    model = VAE(latent_dim=latent_dim).to(device)
    optim = torch.optim.Adam(model.parameters(), lr=lr)

    loader = DataLoader(
        Subset(train_dataset, indices),
        batch_size=batch_size,
        shuffle=True,
        num_workers=0,
    )

    history = []
    for ep in range(1, epochs + 1):
        model.train()
        total, total_bce, total_kld, n = 0, 0.0, 0.0, 0
        for x, _ in loader:
            x = x.to(device)
            optim.zero_grad()
            recon, mu, logvar = model(x)
            bce, kld = vae_loss(recon, x, mu, logvar)
            loss = bce + kld
            loss.backward()
            optim.step()
            total += x.size(0)
            total_bce += bce.item() * x.size(0)
            total_kld += kld.item() * x.size(0)
        n = total
        history.append(
            {
                "epoch": ep,
                "bce": total_bce / n,
                "kld": total_kld / n,
                "elbo": -(total_bce + total_kld) / n,
            }
        )
        print(
            f"  [class {class_id}] epoch {ep}/{epochs}  "
            f"bce={total_bce/n:.2f}  kld={total_kld/n:.2f}  elbo={-(total_bce+total_kld)/n:.2f}"
        )
    return model, history


# ---------------------------------------------------------------------------
# Classification: Bayes rule with ELBO-based p(x | omega_c)
# ---------------------------------------------------------------------------
@torch.no_grad()
def per_image_nll(models, x, device):
    """Return tensor of shape (num_models, batch) with -ELBO per (class, image).

    Higher -ELBO means the class-conditional model finds the image more
    surprising, i.e. lower density p(x | omega_c). The classifier argmaxes
    log p(x | omega) + log P(omega) = -ELBO_c + log P(omega_c) (lower better).
    """
    x = x.to(device)
    neg_elbos = []
    for model in models:
        model.eval()
        mu, logvar = model.encode(x)
        z = model.reparameterize(mu, logvar)
        recon = model.decode(z)
        bce = F.binary_cross_entropy(recon, x, reduction="none")
        bce = bce.view(x.size(0), -1).sum(dim=1)
        kld = -0.5 * torch.sum(1 + logvar - mu.pow(2) - logvar.exp(), dim=1)
        neg_elbos.append((bce + kld).cpu())
    return torch.stack(neg_elbos, dim=0)  # (C, N)


@torch.no_grad()
def classify(models, x, log_prior):
    """Return predicted class for each image in x (NCHW)."""
    neg_elbo = per_image_nll(models, x, x.device if torch.cuda.is_available() else torch.device("cpu"))  # placeholder
    return neg_elbo


@torch.no_grad()
def evaluate(models, test_dataset, indices_by_class, log_prior, device, batch_size=256):
    """Compute test accuracy by scanning the whole test set and predicting
    argmin_c (-ELBO_c + log P(omega_c) = -ELBO_c - log(1/P(omega_c)))."""
    correct = 0
    total = 0
    confusion = np.zeros((10, 10), dtype=np.int64)
    # Pre-collect all test images & labels
    xs, ys = [], []
    for c in range(10):
        for i in indices_by_class[c]:
            xs.append(test_dataset[i][0])
            ys.append(c)
    xs = torch.stack(xs)
    ys = torch.tensor(ys)

    for start in range(0, xs.size(0), batch_size):
        end = min(start + batch_size, xs.size(0))
        xb = xs[start:end].to(device)
        yb = ys[start:end]
        neg_elbo = per_image_nll(models, xb, device)  # (10, B)
        # Add log prior, then argmax = argmin of negative
        scores = neg_elbo - log_prior.view(-1, 1).to(neg_elbo.device)
        preds = scores.argmin(dim=0).cpu().numpy()
        labels = yb.numpy()
        correct += int((preds == labels).sum())
        total += int(labels.size)
        for p, l in zip(preds, labels):
            confusion[p, l] += 1
    return correct / total, confusion


# ---------------------------------------------------------------------------
# Visualization helpers
# ---------------------------------------------------------------------------
@torch.no_grad()
def sample_from_each_class(models, device, n_per_class=8, latent_dim=20):
    """Generate n_per_class random samples from each class-conditional VAE."""
    rows = []
    for c, m in enumerate(models):
        m.eval()
        z = torch.randn(n_per_class, latent_dim, device=device)
        imgs = m.decode(z).cpu()
        rows.append(imgs)
    return torch.cat(rows, dim=0)  # (C*n_per_class, 1, 28, 28)


@torch.no_grad()
def reconstruct_examples(models, test_dataset, indices_by_class, device):
    """For each class, pick a real test image and reconstruct it with that
    class's VAE (and with one wrong-class VAE for visual contrast)."""
    chosen = []
    for c in range(10):
        idx = indices_by_class[c][0]
        chosen.append(test_dataset[idx][0])
    x = torch.stack(chosen).to(device)
    recons = []
    for c, m in enumerate(models):
        m.eval()
        mu, logvar = m.encode(x)
        z = m.reparameterize(mu, logvar)
        recon = m.decode(z).cpu()
        recons.append(recon)
    return x.cpu(), torch.stack(recons)  # (C, N, 1, 28, 28)


def save_sample_grid(samples, path, n_per_class=8):
    """Save a (C, n_per_class) grid of generated samples."""
    fig, axes = plt.subplots(10, n_per_class, figsize=(n_per_class * 1.2, 10 * 1.2))
    for c in range(10):
        for j in range(n_per_class):
            img = samples[c * n_per_class + j].squeeze().numpy()
            axes[c, j].imshow(img, cmap="gray")
            axes[c, j].axis("off")
        axes[c, 0].set_ylabel(f"{c}", rotation=0, fontsize=12, labelpad=20)
    fig.suptitle("Random samples from each class-conditional VAE (rows = class)", y=0.995)
    fig.tight_layout()
    fig.savefig(path, dpi=150, bbox_inches="tight")
    plt.close(fig)


def save_confusion(confusion, path):
    fig, ax = plt.subplots(figsize=(6, 6))
    im = ax.imshow(confusion, cmap="Blues")
    ax.set_xlabel("True label")
    ax.set_ylabel("Predicted label")
    ax.set_xticks(range(10))
    ax.set_yticks(range(10))
    for i in range(10):
        for j in range(10):
            ax.text(
                j, i, str(confusion[i, j]),
                ha="center", va="center",
                color="white" if confusion[i, j] > confusion.max() / 2 else "black",
                fontsize=8,
            )
    fig.colorbar(im, ax=ax, fraction=0.046, pad=0.04)
    fig.suptitle("Confusion matrix on MNIST test set")
    fig.tight_layout()
    fig.savefig(path, dpi=150, bbox_inches="tight")
    plt.close(fig)


def save_training_curves(histories, path):
    fig, axes = plt.subplots(1, 2, figsize=(11, 4))
    for c, hist in enumerate(histories):
        epochs = [h["epoch"] for h in hist]
        bce = [h["bce"] for h in hist]
        kld = [h["kld"] for h in hist]
        axes[0].plot(epochs, bce, marker="o", label=str(c))
        axes[1].plot(epochs, kld, marker="o", label=str(c))
    axes[0].set_title("Reconstruction term (BCE) per class")
    axes[1].set_title("KL term per class")
    for ax in axes:
        ax.set_xlabel("Epoch")
        ax.set_ylabel("Nats / image")
        ax.legend(fontsize=7, ncol=2, loc="upper right")
        ax.grid(alpha=0.3)
    fig.tight_layout()
    fig.savefig(path, dpi=150, bbox_inches="tight")
    plt.close(fig)


def save_recon_grid(x, recons, path, n=10):
    """Top row: real images. Lower rows: reconstruction by each class VAE."""
    fig, axes = plt.subplots(11, n, figsize=(n * 1.2, 11 * 1.2))
    for j in range(n):
        axes[0, j].imshow(x[j].squeeze().numpy(), cmap="gray")
        axes[0, j].axis("off")
        axes[0, j].set_title("real" if j == 0 else "", fontsize=9)
    for c in range(10):
        for j in range(n):
            axes[c + 1, j].imshow(recons[c, j].squeeze().numpy(), cmap="gray")
            axes[c + 1, j].axis("off")
        axes[c + 1, 0].set_ylabel(f"vae_{c}", rotation=0, fontsize=10, labelpad=20)
    fig.suptitle("Each column = one test image (true class = row label). Each lower row shows that image reconstructed by class-c VAE.", y=0.995)
    fig.tight_layout()
    fig.savefig(path, dpi=150, bbox_inches="tight")
    plt.close(fig)


# ---------------------------------------------------------------------------
# Main
# ---------------------------------------------------------------------------
def main():
    p = argparse.ArgumentParser()
    p.add_argument("--epochs", type=int, default=5)
    p.add_argument("--batch-size", type=int, default=128)
    p.add_argument("--lr", type=float, default=1e-3)
    p.add_argument("--latent-dim", type=int, default=20)
    p.add_argument("--data-root", type=str, default="./_data")
    p.add_argument("--out-dir", type=str, default="results")
    args = p.parse_args()

    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    print(f"Device: {device}")
    out_dir = Path(args.out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)

    print("Loading MNIST ...")
    train_set, test_set = make_loaders(batch_size=args.batch_size, root=args.data_root)
    train_idx = get_class_indices(train_set)
    test_idx = get_class_indices(test_set)

    # Class priors from training set
    n_train = len(train_set)
    counts = np.array([len(train_idx[c]) for c in range(10)], dtype=np.float64)
    priors = counts / counts.sum()
    log_prior = torch.log(torch.tensor(priors, dtype=torch.float64))
    print("Class priors:", {c: float(priors[c]) for c in range(10)})

    print(f"Training {10} class-conditional VAEs, {args.epochs} epochs each ...")
    models = []
    histories = []
    t0 = time.time()
    for c in range(10):
        print(f"\n--- Class {c}  ({len(train_idx[c])} training images) ---")
        model, hist = train_one_class(
            c, train_set, train_idx[c],
            epochs=args.epochs, batch_size=args.batch_size, lr=args.lr,
            device=device, latent_dim=args.latent_dim,
        )
        models.append(model)
        histories.append(hist)
    train_seconds = time.time() - t0
    print(f"\nTraining done in {train_seconds:.1f} s.")

    # Save training curves
    save_training_curves(histories, out_dir / "training_curves.png")

    print("\nEvaluating on MNIST test set ...")
    acc, confusion = evaluate(models, test_set, test_idx, log_prior, device)
    print(f"Test accuracy: {acc*100:.2f}%  ({int(acc*len(test_set))} / {len(test_set)})")
    save_confusion(confusion, out_dir / "confusion_matrix.png")

    # Save a few visualisation artefacts
    print("Saving generated samples ...")
    samples = sample_from_each_class(models, device, n_per_class=8, latent_dim=args.latent_dim)
    save_sample_grid(samples, out_dir / "generated_samples.png", n_per_class=8)

    print("Saving reconstruction grid ...")
    x, recons = reconstruct_examples(models, test_set, test_idx, device)
    save_recon_grid(x, recons, out_dir / "reconstructions.png", n=10)

    # Save model checkpoints (small) and metrics
    for c, m in enumerate(models):
        torch.save(m.state_dict(), out_dir / f"vae_class{c}.pt")
    metrics = {
        "test_accuracy": float(acc),
        "confusion_matrix": confusion.tolist(),
        "priors": priors.tolist(),
        "epochs": args.epochs,
        "batch_size": args.batch_size,
        "lr": args.lr,
        "latent_dim": args.latent_dim,
        "train_seconds": train_seconds,
        "n_train": n_train,
        "n_test": len(test_set),
    }
    with open(out_dir / "metrics.json", "w") as f:
        json.dump(metrics, f, indent=2)
    # Plain text metrics for the report
    with open(out_dir / "metrics.txt", "w") as f:
        f.write(f"Test accuracy: {acc*100:.2f}%  ({int(acc*len(test_set))} / {len(test_set)})\n")
        f.write(f"Training time: {train_seconds:.1f} s on {device}\n")
        f.write(f"Epochs per class: {args.epochs}\n")
        f.write(f"Batch size: {args.batch_size}\n")
        f.write(f"Learning rate: {args.lr}\n")
        f.write(f"Latent dim: {args.latent_dim}\n")
        f.write("Per-class priors (from training set):\n")
        for c in range(10):
            f.write(f"  P(omega_{c}) = {priors[c]:.4f}  ({int(counts[c])} images)\n")
    print("Done. Artifacts in", out_dir)


if __name__ == "__main__":
    main()
